// Builds the StrataPay logo from one source of truth:
//   mark  = a rounded tile cut into three wavy strata (fees settling into layers you can spend)
//   words = "StrataPay" in Geist Medium, outlined to paths (no web font needed)
// Outputs:
//   src/components/brand/logo-data.ts   paths + viewBoxes used by <Logo />
//   public/brand/logo.svg               brand lockup (mint mark, light wordmark)
//   public/brand/logo-light.svg         lockup for light backgrounds
//   public/brand/logo-500.png           500x500 on the brand background
//   public/brand/logo-500-transparent.png
//   public/favicon.svg                  the mark alone
// Run: node scripts/build-logo.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';
import { Resvg } from '@resvg/resvg-js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ttf = fs.readFileSync(path.join(root, 'scripts/fonts/Geist-Medium.ttf'));
const font = opentype.parse(ttf.buffer.slice(ttf.byteOffset, ttf.byteOffset + ttf.byteLength));

// Brand tokens (mirror src/styles/tokens.css)
const BRAND = { bg: '#030806', ink: '#f4f8f5', mint: '#7fe3a8', deep: '#0f6b41' };

// ---- mark, drawn on a 40 x 40 grid: tile x/y 4..36, corner radius 9 ----
// Three layers share two wave boundaries; opacity rises toward the bottom (the settled layer).
const MARK_VIEWBOX = '4 4 32 32';
const MARK_LAYERS = [
  { d: 'M4 15V13A9 9 0 0 1 13 4H27A9 9 0 0 1 36 13V13.4C31 10.4 26 10.6 20 14C14 17.4 9 17.6 4 15Z', opacity: 0.42 },
  { d: 'M4 16.6C9 19.2 14 19 20 15.6C26 12.2 31 12 36 15V22.4C31 19.4 26 19.6 20 23C14 26.4 9 26.6 4 24Z', opacity: 0.7 },
  { d: 'M4 25.6C9 28.2 14 28 20 24.6C26 21.2 31 21 36 24V27A9 9 0 0 1 27 36H13A9 9 0 0 1 4 27Z', opacity: 1 },
];

// ---- wordmark ----
const FONT_SIZE = 40;
const TRACKING = -0.02 * FONT_SIZE;
function outline(text) {
  const glyphs = font.stringToGlyphs(text);
  const full = new opentype.Path();
  const parts = [];
  let x = 0;
  glyphs.forEach((g, i) => {
    const p = g.getPath(x, 0, FONT_SIZE);
    parts.push(p.toPathData(2));
    full.extend(p);
    const kern = i < glyphs.length - 1 ? font.getKerningValue(g, glyphs[i + 1]) : 0;
    x += ((g.advanceWidth + kern) / font.unitsPerEm) * FONT_SIZE + TRACKING;
  });
  return { d: parts.join(''), bb: full.getBoundingBox() };
}
const word = outline('StrataPay');
const wb = word.bb; // y1 = cap top (negative), y2 = descender bottom of "y"
const r = (n) => Math.round(n * 100) / 100;
const WORD_VIEWBOX = `${r(wb.x1)} ${r(wb.y1)} ${r(wb.x2 - wb.x1)} ${r(wb.y2 - wb.y1)}`;

// Lockup: mark sits on the baseline and stands a little taller than the caps.
const capH = (font.tables.os2.sCapHeight / font.unitsPerEm) * FONT_SIZE;
const markSize = capH * 1.12;
const markScale = markSize / 32;
const gap = FONT_SIZE * 0.26;
const rawTop = -wb.y1 - capH * 1.06;
const pad = Math.max(0, -rawTop); // grow the box if the mark rises above the caps
const baseline = -wb.y1 + pad; // y of the baseline inside the lockup box
const markTop = rawTop + pad;
const lockW = markSize + gap + (wb.x2 - wb.x1);
const lockH = wb.y2 - wb.y1 + pad;
const LOCKUP = {
  viewBox: `0 0 ${r(lockW)} ${r(lockH)}`,
  markTransform: `translate(0 ${r(markTop)}) scale(${r(markScale * 1000) / 1000}) translate(-4 -4)`,
  wordTransform: `translate(${r(markSize + gap - wb.x1)} ${r(baseline)})`,
};

// ---- write TS data ----
const ts = `// Generated by scripts/build-logo.mjs. Do not edit by hand.
export const MARK_VIEWBOX = '${MARK_VIEWBOX}';
export const MARK_LAYERS = ${JSON.stringify(MARK_LAYERS, null, 2)} as const;
export const WORD_VIEWBOX = '${WORD_VIEWBOX}';
export const WORD_PATH = '${word.d}';
export const LOCKUP = ${JSON.stringify(LOCKUP, null, 2)} as const;
`;
fs.mkdirSync(path.join(root, 'src/components/brand'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/components/brand/logo-data.ts'), ts);

// ---- SVG files ----
const markSvg = (fill) => MARK_LAYERS.map((l) => `<path d="${l.d}" fill="${fill}" fill-opacity="${l.opacity}"/>`).join('');
const lockupSvg = (markFill, wordFill) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${LOCKUP.viewBox}" role="img" aria-label="StrataPay">` +
  `<g transform="${LOCKUP.markTransform}">${markSvg(markFill)}</g>` +
  `<g transform="${LOCKUP.wordTransform}"><path d="${word.d}" fill="${wordFill}"/></g></svg>`;

fs.mkdirSync(path.join(root, 'public/brand'), { recursive: true });
fs.writeFileSync(path.join(root, 'public/brand/logo.svg'), lockupSvg(BRAND.mint, BRAND.ink));
fs.writeFileSync(path.join(root, 'public/brand/logo-light.svg'), lockupSvg(BRAND.deep, BRAND.bg));
fs.writeFileSync(
  path.join(root, 'public/favicon.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="16" fill="${BRAND.bg}"/>` +
    `<g transform="translate(10 10) scale(1.375) translate(-4 -4)">${markSvg(BRAND.mint)}</g></svg>`,
);

// ---- 500 x 500 PNG exports (lockup centred, ~12% padding) ----
const s = (500 * 0.76) / lockW;
const ox = (500 - lockW * s) / 2;
const oy = (500 - lockH * s) / 2;
const square = (bg) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="500" height="500" viewBox="0 0 500 500">` +
  (bg ? `<rect width="500" height="500" fill="${bg}"/>` : '') +
  `<g transform="translate(${r(ox)} ${r(oy)}) scale(${r(s * 1000) / 1000})">` +
  `<g transform="${LOCKUP.markTransform}">${markSvg(BRAND.mint)}</g>` +
  `<g transform="${LOCKUP.wordTransform}"><path d="${word.d}" fill="${BRAND.ink}"/></g></g></svg>`;
for (const [name, bg] of [['logo-500.png', BRAND.bg], ['logo-500-transparent.png', null]]) {
  const png = new Resvg(square(bg), { fitTo: { mode: 'width', value: 500 }, background: bg ? undefined : 'rgba(0,0,0,0)' }).render().asPng();
  fs.writeFileSync(path.join(root, 'public/brand', name), png);
}
console.log('logo built', { WORD_VIEWBOX, LOCKUP });
